class FavoritModel {

  final String uuid;
  final String name;
  final String description;
  final String category;
  final String brand;
  final double price;
  final int count;
  final String imageUrl;

  const FavoritModel({
    required this.uuid,
    required this.name,
    required this.description,
    required this.category,
    required this.brand,
    required this.count,
    required this.price,
    required this.imageUrl
});


}